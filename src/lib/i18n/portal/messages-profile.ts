export const messagesProfileText = { tr, en };

export type MessagesProfileText = typeof tr;

/** Older profiles stored the preparatory year without the "(ELS)" suffix. */
const LEGACY_CLASS_YEARS: Record<string, string> = { "Hazırlık": "Hazırlık (ELS)" };

/** Stored department value to a label in the given language (unknown values are shown as typed). */
export function localizeDepartment(value: string | null | undefined, locale: SupportedLocale): string | null {
  return departmentLabel(value, locale);
}

/** Stored class-year value to a label in the given language (unknown values are shown as typed). */
export function localizeClassYear(value: string | null | undefined, locale: SupportedLocale): string | null {
  if (!value) return null;
  const key = LEGACY_CLASS_YEARS[value] ?? value;
  return messagesProfileText[locale].classYears[key] ?? value;
}
